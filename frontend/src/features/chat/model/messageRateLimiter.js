/**
 * Локальне дзеркало серверного rate-limit з
 * backend/src/sockets/chat.socket.js (RATE_LIMIT_WINDOW_MS /
 * RATE_LIMIT_MAX_MESSAGES). Раніше ліміт перевірявся ЛИШЕ на сокеті —
 * користувач просто не розумів, чому повідомлення "не полетіло"
 * (сервер відповідав ack{success:false}, але composer при цьому лише
 * показував текст помилки постфактум, без попередження заздалегідь і
 * без зворотного відліку). Ця копія дозволяє:
 *
 *  1. миттєво, без походу на сервер, зрозуміти "ще можна надсилати
 *     чи вже ні" — і не витрачати даремно мережевий запит, який
 *     сервер все одно відхилить;
 *  2. дати composer'у число (retryAfterMs), щоб показати користувачу
 *     живий зворотний відлік, а не мовчання.
 *
 * ВАЖЛИВО тримати ці два числа рівними значенням на бекенді. Якщо вони
 * розійдуться — гірше не стане з точки зору безпеки (фінальне рішення
 * завжди за сервером, див. useChatSocket.js: серверна відповідь із
 * кодом RATE_LIMITED/MUTED теж запускає кулдаун), просто UX буде
 * трохи менш точним (клієнт дозволить те, що сервер потім відхилить,
 * або навпаки — заблокує раніше, ніж реально потрібно).
 */
const RATE_LIMIT_WINDOW_MS = 10_000;
const RATE_LIMIT_MAX_MESSAGES = 20;

let timestamps = [];

/**
 * registerSend — викликається безпосередньо перед спробою відправлення.
 * Повертає:
 *   null         — відправлення дозволено, мітку часу записано;
 *   retryAfterMs — відправлення поки заборонено, стільки мс залишилося
 *                  чекати (мітка НЕ записується — повторний виклик до
 *                  завершення кулдауну поверне те саме, а не буде
 *                  тихо накопичувати зайві мітки).
 */
export function registerSend() {
  const now = Date.now();
  timestamps = timestamps.filter((t) => now - t < RATE_LIMIT_WINDOW_MS);

  if (timestamps.length >= RATE_LIMIT_MAX_MESSAGES) {
    const oldest = timestamps[0];
    return RATE_LIMIT_WINDOW_MS - (now - oldest);
  }

  timestamps.push(now);
  return null;
}
