/**
 * Локальное зеркало серверного rate-limit из
 * backend/src/sockets/chat.socket.js (RATE_LIMIT_WINDOW_MS /
 * RATE_LIMIT_MAX_MESSAGES). Раньше лимит проверялся ТОЛЬКО на сокете —
 * пользователь просто не понимал, почему сообщение "не улетело"
 * (сервер отвечал ack{success:false}, но composer при этом лишь
 * показывал текст ошибки постфактум, без предупреждения заранее и без
 * обратного отсчёта). Эта копия позволяет:
 *
 *  1. мгновенно, без похода на сервер, понять "ещё можно отправлять
 *     или уже нет" — и не тратить впустую сетевой запрос, который
 *     сервер всё равно отклонит;
 *  2. дать composer'у число (retryAfterMs), чтобы показать пользователю
 *     живой обратный отсчёт, а не молчание.
 *
 * ВАЖНО держать эти два числа равными значениям на бэкенде. Если они
 * разойдутся — хуже не будет с точки зрения безопасности (финальное
 * решение всегда за сервером, см. useChatSocket.js: серверный ответ с
 * кодом RATE_LIMITED/MUTED тоже запускает кулдаун), просто UX будет
 * чуть менее точным (клиент разрешит то, что сервер потом отклонит,
 * либо наоборот — заблокирует раньше, чем реально нужно).
 */
const RATE_LIMIT_WINDOW_MS = 10_000;
const RATE_LIMIT_MAX_MESSAGES = 20;

let timestamps = [];

/**
 * registerSend — вызывается непосредственно перед попыткой отправки.
 * Возвращает:
 *   null         — отправка разрешена, метка времени записана;
 *   retryAfterMs — отправка пока запрещена, столько мс осталось ждать
 *                  (метка НЕ записывается — повторный вызов до
 *                  истечения кулдауна вернёт то же самое, а не будет
 *                  тихо копить лишние метки).
 */
export function registerSend() {
  const now = Date.now();
  timestamps = timestamps.filter((t) => now - t < RATE_LIMIT_WINDOW_MS);

  if (timestamps.length >= RATE_LIMIT_MAX_MESSAGES) {
    const oldest = timestamps[0];
    return RATE_LIMIT_WINDOW_MS - (now - oldest);
  }

  timestamps.push(now);
  return null;
}
