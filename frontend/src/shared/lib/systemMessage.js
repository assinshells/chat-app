// Допоміжні дані для рендеру системних повідомлень (вхід/перехід/
// вихід) — див. widgets/chat-conversation/ui/ChatConversation.jsx.
//
// Раніше текст залежав від статі користувача (увійшов/увійшла тощо),
// але це давало неправильний порядок слів і зайву складність — тепер
// фрази нейтральні, gender у payload події більше не передається
// (див. backend sockets/chat.socket.js).
export const SYSTEM_EVENTS = Object.freeze({
  JOIN: "join",
  SWITCH: "switch",
  LEAVE: "leave",
});

/**
 * hasRoomLink — для яких подій у повідомленні є клікабельна назва
 * кімнати. Для 'join' (вхід у чат) назву кімнати не показуємо —
 * достатньо привітання, кімната і так видна з контексту відкритої
 * вкладки; для 'switch' назва — це і є суть повідомлення (куди
 * перейшов), тому вона показується і клікабельна; для 'leave' кімнати
 * в тексті немає взагалі (користувач покинув чат повністю).
 */
export function hasRoomLink(event) {
  return event === SYSTEM_EVENTS.SWITCH;
}
