// Візуально невідрізнювані латинські літери, якими часто замінюють
// кирилицю, щоб обійти простий фільтр за словником (a -> а, e -> е...).
const LATIN_TO_CYRILLIC_LOOKALIKES = Object.freeze({
  a: "а",
  b: "ь",
  c: "с",
  e: "е",
  h: "н",
  k: "к",
  m: "м",
  o: "о",
  p: "р",
  t: "т",
  x: "х",
  y: "у",
});

// Часті "leet"-заміни цифрами/символами всередині слова (3 -> е, 0 -> о...).
const LEET_TO_LETTER = Object.freeze({
  "0": "о",
  "1": "і",
  "3": "е",
  "4": "ч",
  "6": "б",
  "@": "а",
  $: "с",
});

const CYRILLIC_LETTER = /[а-яіїєґ]/;

/**
 * normalizeWord — нормалізація ОДНОГО токена (вже відокремленого від
 * решти тексту пробілом), безпечна для склеювання з усім текстом
 * назад через один пробіл:
 *
 *  1. нижній регістр, ё -> е;
 *  2. латинські літери-омогліфи і leet-цифри/символи -> кирилиця
 *     ("cука" / "c9ка" -> "сука"), оскільки заміна йде посимвольно і
 *     не потребує знання меж слова;
 *  3. крапки/дефіси/підкреслення/зірочки ВСЕРЕДИНІ слова прибираються
 *     ("с.у.к.а", "с-у-к-а" як ОДИН токен без пробілів) — частий прийом
 *     обходу, що не зачіпає пробіли між різними словами;
 *  4. 3+ поспіль однакових символи згортаються до 2 ("сууукааа" ->
 *     "суука") — подвійні літери у звичайних словах ("клас", "світанок")
 *     не ламаються.
 */
function normalizeWord(word) {
  let result = String(word ?? "").toLowerCase().replace(/ё/g, "е");

  result = result.replace(
    /[a-z0-9@$]/g,
    (ch) => LATIN_TO_CYRILLIC_LOOKALIKES[ch] ?? LEET_TO_LETTER[ch] ?? ch,
  );

  result = result.replace(/[.\-_*]+/g, "");
  result = result.replace(/(.)\1{2,}/g, "$1$1");

  return result;
}

/**
 * normalizeForModeration — приводить УВЕСЬ текст до вигляду, зручного
 * для порівняння зі словником. На відміну від normalizeWord, працює на
 * рівні всього повідомлення і вирішує одне додаткове завдання: ловить
 * "розбиті по літерах" слова, набрані ЧЕРЕЗ ПРОБІЛ ("с у к а",
 * "с у.к а") — які normalizeWord як окремі токени не впіймає,
 * адже кожна літера сама по собі не схожа на лайку.
 *
 * Розділювачі між словами (пробіли) НЕ прибираються глобально — це
 * важливо: якби все повідомлення згорталося в один рядок без
 * пробілів, "випив хересу вчора" перетворилося б на "випивхересувчора",
 * і безневинне "хересу" хибно впіймалося б як частина слова зі словом-
 * винятком, що втратило межі (див. profanity.filter.js, де exceptions
 * віднімаються ПОСЛІВНО). Натомість склеюються лише поспіль розташовані
 * однобуквені кириличні токени (3 і більше — звичайний текст такими
 * серіями практично не пишуть), а нормальні багатобуквені слова
 * залишаються окремими токенами через пробіл.
 */
export function normalizeForModeration(text) {
  const rawWords = String(text ?? "").split(/\s+/).filter(Boolean);
  const words = rawWords.map(normalizeWord);

  const merged = [];
  let i = 0;
  while (i < words.length) {
    if (words[i].length === 1 && CYRILLIC_LETTER.test(words[i])) {
      let j = i;
      let run = "";
      while (j < words.length && words[j].length === 1 && CYRILLIC_LETTER.test(words[j])) {
        run += words[j];
        j += 1;
      }
      if (j - i >= 3) {
        merged.push(run);
        i = j;
        continue;
      }
    }
    merged.push(words[i]);
    i += 1;
  }

  return merged.join(" ");
}

/**
 * countUppercaseRatio — частка великих літер серед усіх літерних
 * символів вихідного (ще не нормалізованого до нижнього регістру)
 * тексту. Нелітерні символи (цифри, пунктуація, емодзі) в підрахунок
 * не входять — інакше "!!!" або "12:00" спотворювали б частку.
 */
export function countUppercaseRatio(text) {
  const letters = String(text ?? "").match(/\p{L}/gu) ?? [];
  if (letters.length === 0) return 0;

  const uppercase = letters.filter((ch) => ch === ch.toUpperCase() && ch !== ch.toLowerCase());
  return uppercase.length / letters.length;
}
