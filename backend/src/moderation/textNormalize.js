// Визуально неотличимые латинские буквы, которыми часто заменяют
// кириллицу, чтобы обойти простой фильтр по словарю (a -> а, e -> е...).
const LATIN_TO_CYRILLIC_LOOKALIKES = Object.freeze({
  a: "а",
  b: "ь",
  c: "с",
  e: "е",
  h: "н",
  k: "к",
  m: "м",
  o: "о",
  p: "р",
  t: "т",
  x: "х",
  y: "у",
});

// Частые "leet"-замены цифрами/символами внутри слова (3 -> е, 0 -> о...).
const LEET_TO_LETTER = Object.freeze({
  "0": "о",
  "1": "і",
  "3": "е",
  "4": "ч",
  "6": "б",
  "@": "а",
  $: "с",
});

const CYRILLIC_LETTER = /[а-яіїєґ]/;

/**
 * normalizeWord — нормализация ОДНОГО токена (уже отделённого от
 * остального текста пробелом), безопасная для склейки со всем текстом
 * обратно через один пробел:
 *
 *  1. нижний регистр, ё -> е;
 *  2. латинские буквы-омоглифы и leet-цифры/символы -> кириллица
 *     ("cука" / "c9ка" -> "сука"), т.к. подмена идёт посимвольно и не
 *     требует знать границы слова;
 *  3. точки/дефисы/подчёркивания/звёздочки ВНУТРИ слова убираются
 *     ("с.у.к.а", "с-у-к-а" как ОДИН токен без пробелов) — частый приём
 *     обхода, не задевающий пробелы между разными словами;
 *  4. 3+ подряд одинаковых символа схлопываются до 2 ("сууукааа" ->
 *     "суука") — двойные буквы в обычных словах ("клас", "рассвет")
 *     не ломаются.
 */
function normalizeWord(word) {
  let result = String(word ?? "").toLowerCase().replace(/ё/g, "е");

  result = result.replace(
    /[a-z0-9@$]/g,
    (ch) => LATIN_TO_CYRILLIC_LOOKALIKES[ch] ?? LEET_TO_LETTER[ch] ?? ch,
  );

  result = result.replace(/[.\-_*]+/g, "");
  result = result.replace(/(.)\1{2,}/g, "$1$1");

  return result;
}

/**
 * normalizeForModeration — приводит ВЕСЬ текст к виду, удобному для
 * сравнения со словарём. В отличие от normalizeWord, работает на
 * уровне всего сообщения и решает одну дополнительную задачу: ловит
 * "разбитые по буквам" слова, набранные ЧЕРЕЗ ПРОБЕЛ ("с у к а",
 * "с у.к а") — которые normalizeWord как отдельные токены не поймает,
 * ведь каждая буква сама по себе не похожа на мат.
 *
 * Разделители между словами (пробелы) НЕ убираются глобально — это
 * важно: если бы всё сообщение схлопывалось в одну строку без
 * пробелов, "выпил хереса вчера" превратилось бы в "выпилхересавчера",
 * и безобидное "хереса" ложно поймалось бы как часть слова со словом-
 * исключением, потерявшим границы (см. profanity.filter.js, где
 * exceptions вычитаются ПОСЛОВНО). Вместо этого склеиваются только
 * подряд идущие однобуквенные кириллические токены (3 и более —
 * обычный текст такими сериями практически не пишут), а нормальные
 * многобуквенные слова остаются раздельными токенами через пробел.
 */
export function normalizeForModeration(text) {
  const rawWords = String(text ?? "").split(/\s+/).filter(Boolean);
  const words = rawWords.map(normalizeWord);

  const merged = [];
  let i = 0;
  while (i < words.length) {
    if (words[i].length === 1 && CYRILLIC_LETTER.test(words[i])) {
      let j = i;
      let run = "";
      while (j < words.length && words[j].length === 1 && CYRILLIC_LETTER.test(words[j])) {
        run += words[j];
        j += 1;
      }
      if (j - i >= 3) {
        merged.push(run);
        i = j;
        continue;
      }
    }
    merged.push(words[i]);
    i += 1;
  }

  return merged.join(" ");
}

/**
 * countUppercaseRatio — доля заглавных букв среди всех буквенных
 * символов исходного (ещё не нормализованного к нижнему регистру)
 * текста. Небуквенные символы (цифры, пунктуация, эмодзи) в подсчёт не
 * входят — иначе "!!!" или "12:00" искажали бы долю.
 */
export function countUppercaseRatio(text) {
  const letters = String(text ?? "").match(/\p{L}/gu) ?? [];
  if (letters.length === 0) return 0;

  const uppercase = letters.filter((ch) => ch === ch.toUpperCase() && ch !== ch.toLowerCase());
  return uppercase.length / letters.length;
}
