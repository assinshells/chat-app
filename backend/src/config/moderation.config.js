/**
 * moderationConfig — все пороги автомодератора в одном месте, чтобы их
 * можно было подбирать без правки логики фильтров. Как и rate-limit в
 * chat.socket.js, состояние модерации сейчас живёт в оперативной памяти
 * процесса (см. moderation/moderation.service.js) — для одного
 * backend-инстанса этого достаточно, при масштабировании стоит вынести
 * в Redis по аналогии с OTP-лимитами.
 */
export const moderationConfig = Object.freeze({
  // КАПС: сообщение считается "криком", если оно достаточно длинное и
  // доля заглавных букв среди всех букв превышает threshold. Короткие
  // реплики ("ОК", "ДА", "ЩО?!") не наказываются — не набирают minLength.
  caps: Object.freeze({
    minLength: 10,
    threshold: 0.7,
  }),

  // МАТ: список корней/паттернов лежит в moderation/badWords.data.js.
  // Фильтр можно выключить целиком (например, для стенда/тестов).
  profanity: Object.freeze({
    enabled: true,
  }),

  // СПАМ/ФЛУД:
  //  - duplicate*: повтор одного и того же (после нормализации) текста
  //    несколько раз подряд в течение окна — типичный флуд одной фразой;
  //  - links*: сообщения, состоящие практически только из ссылок —
  //    типичный рекламный спам.
  spam: Object.freeze({
    duplicateWindowMs: 30_000,
    duplicateMaxRepeats: 3, // 3-е повторение подряд считается спамом
    maxLinksPerMessage: 3,
  }),

  // ВРЕМЕННЫЙ МУТ: если пользователь набирает violationsThreshold
  // нарушений (мат/капс/спам) за violationWindowMs — сокет временно
  // "глохнет" на muteDurationMs: сервер отклоняет любые message:send с
  // кодом MUTED и оставшимся временем (retryAfterMs), не проверяя даже
  // содержимое — это и есть эскалация наказания для тех, кто просто
  // подбирает обход фильтра методом проб и ошибок.
  mute: Object.freeze({
    violationsThreshold: 3,
    violationWindowMs: 60_000,
    muteDurationMs: 30_000,
  }),
});
