/**
 * moderationConfig — усі пороги автомодератора в одному місці, щоб їх
 * можна було підбирати без правки логіки фільтрів. Як і rate-limit у
 * chat.socket.js, стан модерації зараз живе в оперативній пам'яті
 * процесу (див. moderation/moderation.service.js) — для одного
 * backend-інстансу цього достатньо, при масштабуванні варто винести
 * в Redis за аналогією з лімітами OTP.
 */
export const moderationConfig = Object.freeze({
  // КАПС: повідомлення вважається "криком", якщо воно достатньо довге і
  // частка великих літер серед усіх літер перевищує threshold. Короткі
  // репліки ("ОК", "ТАК", "ЩО?!") не караються — не набирають minLength.
  caps: Object.freeze({
    minLength: 10,
    threshold: 0.7,
  }),

  // МАТ: список коренів/патернів лежить у moderation/badWords.data.js.
  // Фільтр можна вимкнути повністю (наприклад, для стенду/тестів).
  profanity: Object.freeze({
    enabled: true,
  }),

  // СПАМ/ФЛУД:
  //  - duplicate*: повтор одного й того самого (після нормалізації) тексту
  //    декілька разів поспіль протягом вікна — типовий флуд однією фразою;
  //  - links*: повідомлення, що складаються практично лише з посилань —
  //    типовий рекламний спам.
  spam: Object.freeze({
    duplicateWindowMs: 30_000,
    duplicateMaxRepeats: 3, // 3-є повторення поспіль вважається спамом
    maxLinksPerMessage: 3,
  }),

  // ТИМЧАСОВИЙ МУТ: якщо користувач набирає violationsThreshold
  // порушень (мат/капс/спам) за violationWindowMs — сокет тимчасово
  // "глухне" на muteDurationMs: сервер відхиляє будь-які message:send з
  // кодом MUTED і часом, що залишився (retryAfterMs), навіть не перевіряючи
  // вміст — це і є ескалація покарання для тих, хто просто підбирає
  // обхід фільтра методом проб і помилок.
  mute: Object.freeze({
    violationsThreshold: 3,
    violationWindowMs: 60_000,
    muteDurationMs: 30_000,
  }),
});
